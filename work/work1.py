# [name, age, score_math, score_chinese]
student_info = [
    {'姓名':'小明', '年龄':17, '数学分数':80.5, '语文分数':90.0},
    {'姓名':'小王', '年龄':17, '数学分数':91.5, '语文分数':83.5},
    {'姓名':'小福', '年龄':17, '数学分数':92.5, '语文分数':75.0}
    ]



def average_score(score,list):
    a_score = score / 2
    list['平均成绩'] = a_score
    if a_score > 90:
        level = 'A'
        list['评级'] = level
    elif a_score > 80 and a_score < 89:
        level = 'B'
        list['评级'] = level
    elif a_score > 70 and a_score < 79:
        level = 'C'
        list['评级'] = level
    elif a_score > 60 and a_score < 69:
        level = 'D'
        list['评级'] = level
    else:
        level = 'F'
        list['评级'] = level


for i in student_info:
    sum = 0
    for j in i:
        if type(i.get(j)) == float:
            sum += i[j]
    i['总成绩'] = sum
    average_score(sum, i)
    print(f'姓名：{i["姓名"]}, 年龄：{i["年龄"]}, 数学分数：{i["数学分数"]}, 语文分数：{i["语文分数"]}, 总成绩：{i["总成绩"]}, 平均成绩：{i["平均成绩"]}, 该生等级评定为：{i["评级"]}')





